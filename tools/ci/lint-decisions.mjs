#!/usr/bin/env node
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_ROOT = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const CLASSES = ["feature", "bug-fix", "simplification", "architecture", "process", "testing"];
const LIFECYCLES = ["proposed", "implemented", "rejected", "archived"];
const NOTE_NAME = /^\d{4}-\d{2}-\d{2}-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
const REQUIRED = {
  proposed: [
    "Problem",
    "Proposal",
    "Rationale",
    "Alternatives considered",
    "Impact",
    "Affected components",
    "Approvers",
    "Related records",
  ],
  implemented: [
    "Problem",
    "Decision",
    "Rationale",
    "Alternatives considered",
    "Impact",
    "Affected components",
    "Approvers",
    "Related records",
    "Consequences",
    "Implementation",
    "Verification",
  ],
  rejected: [
    "Problem",
    "Proposal",
    "Rationale",
    "Alternatives considered",
    "Impact",
    "Affected components",
    "Approvers",
    "Related records",
  ],
  archived: [
    "Problem",
    "Decision",
    "Rationale",
    "Alternatives considered",
    "Impact",
    "Affected components",
    "Approvers",
    "Related records",
    "Consequences",
    "Implementation",
    "Verification",
  ],
};
const SKIP_NAMES = new Set(["README.md", "AGENTS.md", "CLAUDE.md"]);

function parseArgs(argv) {
  let root = DEFAULT_ROOT;
  let write = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--write") write = true;
    else if (arg === "--root") {
      root = resolve(argv[i + 1] ?? "");
      i += 1;
    } else if (arg.startsWith("--root=")) {
      root = resolve(arg.slice("--root=".length));
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return { root, write };
}

function walk(dir, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir)) {
    if (name === "templates") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, acc);
    else if (name.endsWith(".md") && !SKIP_NAMES.has(name)) acc.push(path);
  }
  return acc;
}

function sectionBody(src, heading) {
  const marker = `## ${heading}`;
  const start = src.indexOf(marker);
  if (start === -1) return "";
  const after = src.slice(start + marker.length);
  const next = after.search(/^## /m);
  return (next === -1 ? after : after.slice(0, next)).trim();
}

function posixRel(fromDir, toFile) {
  return relative(fromDir, toFile).split(sep).join("/");
}

function renderIndex(root, notes) {
  const indexDir = join(root, "docs/architecture");
  const dates = notes.map((n) => n.filename.slice(0, 10)).sort();
  const last = dates.at(-1) || "2026-08-19";
  const rows = notes
    .slice()
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((n) => {
      const rel = posixRel(indexDir, n.file);
      return `| ${n.id} | ${n.lifecycle} | ${n.title} | [note](${rel}) |`;
    })
    .join("\n");

  return `# Architecture decisions

Status: living
Owner: engineering
Last-reviewed: ${last}

Generated by \`pnpm decisions:index\`. Do not hand-edit the table. This
index is readable, not a second decision store. Authority lives in
[\`.agents/notes\`](../../.agents/notes/README.md).

| ID | Status | Title | Path |
|---|---|---|---|
${rows}

Human architectural review moves high-impact notes into \`implemented/\`.
Proposed records are not authority. IDs are never reused.
`;
}

function main() {
  const { root, write } = parseArgs(process.argv.slice(2));
  const notesRoot = join(root, ".agents/notes");
  const errors = [];
  const notes = [];

  for (const lifecycle of LIFECYCLES) {
    const dir = join(notesRoot, lifecycle);
    if (!existsSync(dir)) errors.push(`missing .agents/notes/${lifecycle}/`);
  }

  const templatesDir = join(notesRoot, "templates");
  for (const [lifecycle, headings] of Object.entries(REQUIRED)) {
    const file = join(templatesDir, `${lifecycle}.md`);
    if (!existsSync(file)) {
      errors.push(`missing .agents/notes/templates/${lifecycle}.md`);
      continue;
    }
    const src = readFileSync(file, "utf8");
    if (!src.startsWith("# Agent Note:")) {
      errors.push(`${file}: template must start with "# Agent Note:"`);
    }
    for (const heading of headings) {
      if (!src.includes(`## ${heading}`)) {
        errors.push(`templates/${lifecycle}.md: missing ## ${heading}`);
      }
    }
  }

  const ids = new Map();
  const filenames = new Map();

  for (const lifecycle of LIFECYCLES) {
    const dir = join(notesRoot, lifecycle);
    for (const file of walk(dir)) {
      const src = readFileSync(file, "utf8");
      const rel = posixRel(root, file);
      const relToLifecycle = relative(dir, file).split(sep);
      if (relToLifecycle.length !== 2) {
        errors.push(`${rel}: notes must live at <class>/<YYYY-MM-DD-slug>.md`);
        continue;
      }
      const [klass, filename] = relToLifecycle;
      if (!CLASSES.includes(klass)) {
        errors.push(`${rel}: class must be one of ${CLASSES.join(", ")}`);
      }
      if (!NOTE_NAME.test(filename)) {
        errors.push(`${rel}: filename must match YYYY-MM-DD-lowercase-slug.md`);
      }

      if (!src.startsWith("# Agent Note:")) {
        errors.push(`${rel}: must start with "# Agent Note:"`);
      }
      const titleMatch = src.match(/^# Agent Note: (.+)$/m);
      const title = titleMatch ? titleMatch[1].trim() : "";
      if (!title) errors.push(`${rel}: missing title`);

      const idMatches = src.match(/^ID: ADR-\d{4}$/gm) || [];
      if (idMatches.length !== 1) {
        errors.push(`${rel}: must have exactly one ID: ADR-NNNN line`);
      }
      const id = (src.match(/^ID: (ADR-\d{4})$/m) || [])[1];
      if (id) {
        if (ids.has(id)) errors.push(`${rel}: duplicate ${id} (also ${ids.get(id)})`);
        else ids.set(id, rel);
      }

      if (filenames.has(filename)) {
        errors.push(`${rel}: slug ${filename} already used by ${filenames.get(filename)}`);
      } else {
        filenames.set(filename, rel);
      }

      const statusLines = src.match(/^Status: .+$/gm) || [];
      if (statusLines.length !== 1) {
        errors.push(`${rel}: must have exactly one Status line`);
      }
      const status = statusLines[0] || "";
      if (lifecycle === "proposed" && status !== "Status: proposed") {
        errors.push(`${rel}: proposed notes need Status: proposed`);
      }
      if (lifecycle === "implemented" && status !== "Status: implemented") {
        errors.push(`${rel}: implemented notes need Status: implemented`);
      }
      if (lifecycle === "rejected" && !/^Status: rejected — .+/.test(status)) {
        errors.push(`${rel}: rejected notes need Status: rejected — <why>`);
      }
      if (lifecycle === "archived") {
        if (status !== "Status: implemented") {
          errors.push(`${rel}: archived notes keep Status: implemented`);
        }
        if (!/^Archived: \d{4}-\d{2}-\d{2}$/m.test(src)) {
          errors.push(`${rel}: archived notes need Archived: YYYY-MM-DD`);
        }
        if (!/^Replacement: .+/m.test(src)) {
          errors.push(`${rel}: archived notes need Replacement:`);
        }
        if (!/^Content-SHA256: [a-f0-9]{64}$/m.test(src)) {
          errors.push(`${rel}: archived notes need Content-SHA256: <64 hex>`);
        }
      }

      for (const heading of REQUIRED[lifecycle]) {
        if (!src.includes(`## ${heading}`)) errors.push(`${rel}: missing ## ${heading}`);
      }

      const alternatives = sectionBody(src, "Alternatives considered").match(/^- \*\*[^*]+\*\*/gm);
      if (!alternatives || alternatives.length < 2) {
        errors.push(`${rel}: Alternatives considered needs at least two real options`);
      }
      const impact = sectionBody(src, "Impact");
      for (const label of ["Security", "Operations", "Data"]) {
        if (!new RegExp(`^- \\*\\*${label}:\\*\\*`, "m").test(impact)) {
          errors.push(`${rel}: Impact missing **${label}:**`);
        }
      }

      if (id && title) {
        notes.push({ id, lifecycle, title, file, filename });
      }
    }
  }

  const indexPath = join(root, "docs/architecture/decisions.md");
  const expected = renderIndex(root, notes);
  if (write) {
    if (errors.length) {
      for (const err of errors) console.error(err);
      process.exit(1);
    }
    mkdirSync(dirname(indexPath), { recursive: true });
    writeFileSync(indexPath, expected);
    process.stdout.write("wrote docs/architecture/decisions.md\n");
    process.stdout.write("ok: decision notes\n");
    return;
  }
  if (!existsSync(indexPath)) {
    errors.push("missing docs/architecture/decisions.md");
  } else if (readFileSync(indexPath, "utf8") !== expected) {
    errors.push("docs/architecture/decisions.md is out of date. Run pnpm decisions:index");
  }

  if (errors.length) {
    for (const err of errors) console.error(err);
    process.exit(1);
  }
  process.stdout.write("ok: decision notes\n");
}

main();
